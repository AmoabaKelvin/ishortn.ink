/**
 * A tenant subdomain of a shared platform (`acme.framer.app`, `x.weebly.com`), where anyone can
 * publish a page. The platform apex and its `www.` host are run by the platform itself.
 */
export function isSharedHostTenant(hostname: string): boolean {
  const host = hostname
    .toLowerCase()
    .replace(/\.$/, "")
    .replace(/^www\./, "");
  return SHARED_HOST_SUFFIXES.some((suffix) => host.endsWith(`.${suffix}`));
}
